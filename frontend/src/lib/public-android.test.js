test('timed-out native write cannot be followed by another pairing, even after its late commit',async()=>{
  vi.useFakeTimers()
  const fetch=vi.fn(async()=>paired());vi.stubGlobal('fetch',fetch)
  const remote=await import('./remote.js'),api=await import('./api.js');await remote.connect(base,'12345678')
  let commit
  secure.set.mockImplementationOnce((key,value)=>new Promise(resolve=>{commit=()=>{secure.values.set(key,value);resolve()}}))
  fetch.mockResolvedValue(paired('user-b','synthetic-b'))
  const pairing=remote.connect(other,'87654321').catch(error=>error)
  await vi.waitFor(()=>expect(commit).toBeTypeOf('function'))
  await vi.advanceTimersByTimeAsync(4001)
  expect(await pairing).toMatchObject({code:'secure-session-restart-required'})
  expect(()=>api.authenticatedCatalogFetch('/api/nutrition/catalog/capabilities')).toThrow()
  const writes=secure.set.mock.calls.length
  await expect(remote.connect('https://third.example','87654321')).rejects.toMatchObject({code:'secure-session-restart-required'})
  commit();await Promise.resolve()
  await expect(remote.loadRemote()).rejects.toMatchObject({code:'secure-session-restart-required'})
  await expect(remote.chooseLocal()).rejects.toMatchObject({code:'secure-session-restart-required'})
  await expect(remote.forgetRemote()).rejects.toMatchObject({code:'secure-session-restart-required'})
  await expect(remote.connect('https://third.example','87654321')).rejects.toMatchObject({code:'secure-session-restart-required'})
  expect(secure.set).toHaveBeenCalledTimes(writes);expect(fetch).toHaveBeenCalledTimes(2)
  expect(JSON.parse([...secure.values.values()][0]).base).toBe(other)
  expect(files.saveRemoteFile).not.toHaveBeenCalled()
})
